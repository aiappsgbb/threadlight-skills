#!/usr/bin/env python3
"""eval_yaml.py — scaffold `evals/azure.eval.yaml` for a Threadlight pilot (#209, #210).

Two evals over one golden set split into an optimizer part and a held-out part:

* ``<agent>-gate``: held-out rows only. The custom rubric gets an explicit
  ``dataMapping`` so the judge sees the trajectory (``sample.output_items``,
  ``sample.tool_calls``) and the expected answer (``item.ground_truth``).
  Without it ``azd ai eval init`` maps a custom rubric to ``sample.output_text``
  only. Paired with ``builtin.task_adherence``, not ``builtin.task_completion``,
  which scores correct refusals and escalations as failures.
* ``<agent>-optimizer-input``: optimizer rows, same evaluators, **no**
  ``dataMapping``. ``azd ai agent optimize --eval`` rejects an evaluator with
  ``dataMapping`` ("optimization cannot represent"). The held-out rows are never
  given to the optimizer.

Subcommands (stdlib only):

    split     golden.jsonl -> <agent>-optimize.jsonl + <agent>-heldout.jsonl
    scaffold  write azure.eval.yaml (and raise the rubric pass_threshold to >= 0.7)
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import sys
from pathlib import Path

MIN_ROWS = 50
HELDOUT_FRACTION = 0.3
MIN_RUBRIC_PASS_THRESHOLD = 0.7
GATE_MAPPING = (
    ("query", "{{item.query}}"),
    ("response", "{{sample.output_items}}"),
    ("ground_truth", "{{item.ground_truth}}"),
    ("tool_calls", "{{sample.tool_calls}}"),
    ("tool_definitions", "{{sample.tool_definitions}}"),
)
GATE_BUILTIN = "builtin.task_adherence"


def _rows(path: Path) -> list[dict]:
    rows = [json.loads(line) for line in path.read_text(encoding="utf-8").splitlines() if line.strip()]
    for index, row in enumerate(rows):
        missing = [k for k in ("name", "query", "ground_truth") if not row.get(k)]
        if missing:
            raise ValueError(f"{path}:{index + 1}: row needs {', '.join(missing)}")
    names = [r["name"] for r in rows]
    if len(set(names)) != len(names):
        raise ValueError(f"{path}: duplicate row names")
    return rows


def split(rows: list[dict], fraction: float = HELDOUT_FRACTION) -> tuple[list[dict], list[dict]]:
    """Deterministic split stratified by ``category`` (else one stratum): each
    stratum sends at least one row to held-out when it has two or more."""
    strata: dict[str, list[dict]] = {}
    for row in rows:
        strata.setdefault(str(row.get("category", "")), []).append(row)
    optimize, heldout = [], []
    for key in sorted(strata):
        members = sorted(strata[key], key=lambda r: hashlib.sha256(r["name"].encode()).hexdigest())
        count = round(len(members) * fraction)
        if len(members) >= 2:
            count = max(1, min(count, len(members) - 1))
        heldout += members[:count]
        optimize += members[count:]
    order = {r["name"]: i for i, r in enumerate(rows)}
    return (sorted(optimize, key=lambda r: order[r["name"]]),
            sorted(heldout, key=lambda r: order[r["name"]]))


def _q(value: str) -> str:
    return json.dumps(value)


def render(agent: str, rubric: str, rubric_source: str, judge: str,
           optimize_file: str, heldout_file: str) -> str:
    """Render azure.eval.yaml. Paths are relative to the YAML file."""
    lines = [
        "# Generated by threadlight-evals scripts/eval_yaml.py. Commit it.",
        f"# {agent}-gate: held-out rows, trajectory-mapped rubric; the release gate.",
        f"# {agent}-optimizer-input: optimizer rows, no dataMapping; only for",
        f"#   azd ai agent optimize --eval {agent}-optimizer-input",
        "evaluators:",
        f"  - name: {rubric}",
        f"    source: {rubric_source}",
        "datasets:",
        f"  - name: {agent}-optimize",
        f"    file: {optimize_file}",
        f"  - name: {agent}-heldout",
        f"    file: {heldout_file}",
        "evals:",
    ]
    for name, dataset, mapped in ((f"{agent}-gate", f"{agent}-heldout", True),
                                  (f"{agent}-optimizer-input", f"{agent}-optimize", False)):
        lines += [
            f"  - name: {name}",
            f"    dataset: {dataset}",
            "    evaluationLevel: turn",
            "    evaluators:",
            f"      - evaluator: {rubric}",
        ]
        if mapped:
            # Stored mappings are immutable: a distinct criterion name keeps them apart.
            lines.append(f"        name: {rubric}-trajectory")
        lines += ["        initializationParameters:", f"          model: {judge}"]
        if mapped:
            lines.append("        dataMapping:")
            lines += [f"          {key}: {_q(value)}" for key, value in GATE_MAPPING]
        lines += [
            f"      - evaluator: {GATE_BUILTIN}",
            "        initializationParameters:",
            f"          model: {judge}",
            "    target:",
            "      type: agent",
            f"      name: {agent}",
        ]
    return "\n".join(lines) + "\n"


def _raise_threshold(rubric_path: Path) -> float | None:
    data = json.loads(rubric_path.read_text(encoding="utf-8"))
    current = data.get("pass_threshold")
    if not isinstance(current, (int, float)) or current < MIN_RUBRIC_PASS_THRESHOLD:
        data["pass_threshold"] = MIN_RUBRIC_PASS_THRESHOLD
        rubric_path.write_text(json.dumps(data, indent=2) + "\n", encoding="utf-8")
        return current
    return None


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    sp = sub.add_parser("split", help="split a golden set into optimize and held-out files")
    sp.add_argument("golden", type=Path)
    sp.add_argument("--agent", required=True)
    sp.add_argument("--out-dir", type=Path, default=Path("evals/datasets"))
    sc = sub.add_parser("scaffold", help="write evals/azure.eval.yaml")
    sc.add_argument("--agent", required=True)
    sc.add_argument("--rubric", required=True, help="custom rubric evaluator name")
    sc.add_argument("--rubric-file", type=Path, required=True, help="rubric JSON (from azd ai eval generate)")
    sc.add_argument("--judge-model", required=True)
    sc.add_argument("--evals-dir", type=Path, default=Path("evals"))
    args = ap.parse_args(argv)

    if args.cmd == "split":
        rows = _rows(args.golden)
        optimize, heldout = split(rows)
        args.out_dir.mkdir(parents=True, exist_ok=True)
        for name, part in (("optimize", optimize), ("heldout", heldout)):
            (args.out_dir / f"{args.agent}-{name}.jsonl").write_text(
                "".join(json.dumps(r) + "\n" for r in part), encoding="utf-8")
        print(f"{len(rows)} rows -> optimize {len(optimize)}, held-out {len(heldout)}")
        if len(rows) < MIN_ROWS:
            print(f"WARNING: {len(rows)} golden rows < {MIN_ROWS}; EVAL-107 stays must-fix", file=sys.stderr)
        return 0

    evals_dir = args.evals_dir
    datasets = evals_dir / "datasets"
    for part in ("optimize", "heldout"):
        if not (datasets / f"{args.agent}-{part}.jsonl").is_file():
            print(f"missing {datasets}/{args.agent}-{part}.jsonl; run `split` first", file=sys.stderr)
            return 2
    rubric = args.rubric_file.resolve()
    raised = _raise_threshold(rubric)
    source = Path(os.path.relpath(rubric, evals_dir.resolve())).as_posix()
    text = render(args.agent, args.rubric, source if source.startswith("..") else f"./{source}",
                  args.judge_model, f"./datasets/{args.agent}-optimize.jsonl",
                  f"./datasets/{args.agent}-heldout.jsonl")
    (evals_dir / "azure.eval.yaml").write_text(text, encoding="utf-8")
    if raised is not None:
        print(f"rubric pass_threshold {raised} -> {MIN_RUBRIC_PASS_THRESHOLD}")
    print(f"wrote {evals_dir / 'azure.eval.yaml'}: {args.agent}-gate, {args.agent}-optimizer-input")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
