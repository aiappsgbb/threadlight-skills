def _spec_scalar(spec: str, key: str) -> str | None:
    """Top-level ``key: value`` from SPEC YAML; quoted values keep a ``#``, comments are dropped."""
    m = re.search(rf"^\s*{key}:[ \t]*(.*)$", spec, re.M)
    if not m:
        return None
    raw = m.group(1).strip()
    if raw[:1] in ("'", '"'):
        end = raw.find(raw[0], 1)
        value = raw[1:end] if end > 0 else raw[1:]
    else:
        value = raw.split(" #", 1)[0].strip()
    return None if value.lower() in ("", "null", "~", "none") else value


def voice_frontend(spec: str) -> tuple[dict[str, str] | None, str | None]:
    """SPEC 11e ``voice_frontend`` as ``(voice config, None)`` or ``(None, ignore reason)``.

    Foundry Hosted Voice is preview, so it needs the same explicit, preview-acknowledged
    user opt-in as ``agent_type: voice`` (skills/_shared/foundry-only-agents.md item 2c).
    An agent-written or incomplete opt-in is not an opt-in: the agent stays text-only.
    """
    requested = (_spec_scalar(spec, "voice_frontend") or "none").lower()
    if requested in ("none", "false", "off"):
        return None, None
    if requested != "hosted-voice":
        raise WorkspaceError(f"SPEC section 11e voice_frontend must be none or hosted-voice, got {requested!r}")
    missing = []
    if (_spec_scalar(spec, "voice_opt_in_source") or "").lower() != "user":
        missing.append("voice_opt_in_source: user")
    if not _spec_scalar(spec, "voice_opt_in_evidence"):
        missing.append("voice_opt_in_evidence")
    if (_spec_scalar(spec, "preview_acknowledged") or "").lower() != "true":
        missing.append("preview_acknowledged: true")
    if missing:
        return None, ("voice_frontend ignored: hosted-voice needs an explicit user opt-in ("
                      + ", ".join(missing) + "); the agent was generated text-only")
    name = _spec_scalar(spec, "voice_name") or VOICE_DEFAULT_NAME
    if not re.fullmatch(r"[a-z]{2,3}-[A-Z]{2}-[A-Za-z0-9:]+", name):
        raise WorkspaceError(f"SPEC section 11e voice_name must be an Azure voice name like {VOICE_DEFAULT_NAME}")
    return {"voice_name": name}, None


def business_rules(spec: str) -> dict[str, str]:
    rules: dict[str, str] = {}
    for m in re.finditer(r"^#{2,4}\s*(BR-\d+)\s*[:\-—]\s*(.+)$", spec, re.M):
        rules.setdefault(m.group(1), m.group(2).strip())
    for m in re.finditer(r"\|\s*\*{0,2}`?(BR-\d+)`?\*{0,2}\s*\|\s*([^|]+)\|", spec):
        rules.setdefault(m.group(1), _strip_ticks(m.group(2)).strip("* "))
    return dict(sorted(rules.items(), key=lambda kv: int(kv[0].split("-")[1])))


def business_rule_bodies(spec: str) -> dict[str, list[str]]:
    """Bullet text under each ``### BR-nnn`` heading, unwrapped, KPI lines dropped."""
    bodies: dict[str, list[str]] = {}
    pattern = r"^#{2,4}[ \t]*(BR-\d+)[ \t]*[:\-—][^\n]*\n(.*?)(?=^#{1,6}\s|^---\s*$|\Z)"
    for m in re.finditer(pattern, spec, re.M | re.S):
        items: list[str] = []
        for line in m.group(2).replace("**", "").splitlines():
            text = line.strip()
            if not text:
                continue
            if text.startswith(("- ", "* ")):
                items.append(text[2:].strip())
            elif items:
                items[-1] += " " + text
            else:
                items.append(text)
        items = [i for i in items if not i.lower().startswith("kpi")]
        if items:
            bodies.setdefault(m.group(1), items)
    return bodies


def _expand_rule_ids(text: str) -> list[str]:
    ids: list[str] = []
    for m in re.finditer(r"BR-(\d+)((?:\s*[,/]\s*\d+)*)", text):
        width = len(m.group(1))
        for num in [m.group(1)] + re.findall(r"\d+", m.group(2)):
            rid = f"BR-{int(num):0{width}d}"
            if rid not in ids:
                ids.append(rid)
    return ids


def scenarios(spec: str) -> list[dict[str, Any]]:
    """SPEC section 9 evaluation scenarios table."""
    m = re.search(r"^#{2,4}\s*Evaluation\s+scenarios[^\n]*\n(.*?)(?=^#{2,4}\s|\Z)", spec, re.M | re.S | re.I)
    block = m.group(1) if m else _section(spec, "9")
    rows: list[dict[str, Any]] = []
    for table in _tables(block):
        header = [h.lower() for h in table[0]]
        if not header or header[0] != "id":
            continue

        def col(*keys: str) -> int | None:
            return next((i for i, h in enumerate(header) if any(k in h for k in keys)), None)

        i_scn, i_in, i_exp = col("scenario"), col("input"), col("expected")
        i_br, i_cat = col("business rule", "brs", "rules"), col("category")
        for row in table[1:]:
            get = lambda i: row[i] if i is not None and i < len(row) else ""  # noqa: E731
            sid = _strip_ticks(row[0])
            if not sid:
                continue
            query = _strip_ticks(get(i_in)) or _strip_ticks(get(i_scn))
            rows.append({
                "id": sid,
                "query": query,
                "expected": _strip_ticks(get(i_exp)),
                "business_rules": _expand_rule_ids(get(i_br)),
                "category": _strip_ticks(get(i_cat)) or "functional",
                "scenario": _strip_ticks(get(i_scn)),
            })
    if not rows:
        raise WorkspaceError("SPEC section 9 has no 'Evaluation scenarios' table")
    return rows


def design_dataset(project_dir: Path) -> list[dict[str, Any]]:
    """Reuse threadlight-design's validated tests/eval_dataset.jsonl verbatim when present."""
    path = project_dir / "tests" / "eval_dataset.jsonl"
    if not path.is_file():
        return []
    rows: list[dict[str, Any]] = []
    for n, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        if not line.strip():
            continue
        try:
            row = json.loads(line)
        except json.JSONDecodeError as exc:
            raise WorkspaceError(f"tests/eval_dataset.jsonl line {n}: {exc}") from exc
        query = row.get("query") or row.get("prompt") or row.get("input")
        if not isinstance(row, dict) or not row.get("id") or not query:
            raise WorkspaceError(f"tests/eval_dataset.jsonl line {n}: needs 'id' and 'query' (or 'prompt')")
        rules = row.get("business_rules") or []
        rows.append({
            "id": str(row["id"]),
            "query": str(query),
            # Structured expectations stay JSON text (str() wrote a Python repr).
            "expected": expected if isinstance(expected := row.get("expected", ""), str)
            else json.dumps(expected, ensure_ascii=False),
            "business_rules": [str(r) for r in rules] if isinstance(rules, list) else _expand_rule_ids(str(rules)),
            "category": str(row.get("category") or "functional"),
            "scenario": str(row.get("scenario", "")),
        })
    return rows


