def design_model(project_dir: Path, spec: str) -> tuple[str, str] | None:
    """(model, version) chosen by threadlight-design: foundation.md section 2, else SPEC 7b."""
    foundation = project_dir / "specs" / "foundation.md"
    if foundation.is_file():
        text = foundation.read_text(encoding="utf-8")
        block = re.search(r"^model:\s*\n((?:[ \t]+.*\n?)+)", text, re.M)
        if block:
            name = re.search(r"^\s+(?:default|name):\s*[\"']?([A-Za-z0-9._-]+)", block.group(1), re.M)
            version = re.search(r"^\s+version:\s*[\"']?([0-9][0-9A-Za-z._-]*)", block.group(1), re.M)
            if name:
                return name.group(1), version.group(1) if version else ""
    m = re.search(r"\*\*Model(?:\s*\+\s*version)?\*\*\s*:?\s*`([A-Za-z0-9._-]+)`\s*(?:\(([0-9][0-9A-Za-z._-]*)\))?",
                  _section(spec, "7b"))
    if m:
        return m.group(1), m.group(2) or ""
    return None


def design_capacity_tpm(project_dir: Path) -> int | None:
    """``capacity_tpm`` from foundation.md section 2 (``50K``, ``1M``, ``400000``), in tokens per minute."""
    foundation = project_dir / "specs" / "foundation.md"
    if not foundation.is_file():
        return None
    block = re.search(r"^model:\s*\n((?:[ \t]+.*\n?)+)", foundation.read_text(encoding="utf-8"), re.M)
    m = re.search(r"^\s+capacity_tpm:\s*[\"']?([0-9][0-9_,]*(?:\.[0-9]+)?)\s*([KkMm])?\b", block.group(1), re.M) if block else None
    if not m:
        return None
    value = float(m.group(1).replace("_", "").replace(",", ""))
    scale = {"k": 1_000, "m": 1_000_000}.get((m.group(2) or "").lower(), 1)
    return int(value * scale) or None


def model_capacity(tpm: int | None) -> tuple[int, str]:
    """GlobalStandard capacity units for main.parameters.json plus a deferred-steps row when raised.

    1 unit = 1,000 TPM. A foundation value below MIN_MODEL_CAPACITY is raised to
    that live-proven floor and the raise is disclosed; none uses the floor.
    """
    if tpm is None:
        return MIN_MODEL_CAPACITY, ""
    units = -(-tpm // 1000)
    if units >= MIN_MODEL_CAPACITY:
        return units, ""
    asked = f"{tpm // 1000:,}K TPM" if tpm % 1000 == 0 else f"{tpm:,} TPM"
    return MIN_MODEL_CAPACITY, (
        f"| Model capacity | raised | `specs/foundation.md` asks for {asked} ({units} units; 1 unit = 1,000 TPM). "
        "The GHCP runtime bursts about 10 model calls of ~8K tokens per case and the Foundry evaluation judge "
        f"shares the deployment; 50 units or less returned 429 in live runs, so `infra/main.parameters.json` "
        f"defaults to {MIN_MODEL_CAPACITY} units ({MIN_MODEL_CAPACITY}K TPM). GlobalStandard is billed per "
        "token, so this raises the rate limit, not a reservation. To follow the foundation exactly: "
        f"`azd env set AZURE_AI_MODEL_CAPACITY {units}`. Confirm regional quota in Phase 3.5. |\n"
    )


