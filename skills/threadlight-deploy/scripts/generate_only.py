def build_eval_config(
    agent: str,
    rules: dict[str, str],
    scen: list[dict[str, Any]],
    bodies: dict[str, list[str]] | None = None,
) -> dict[str, Any]:
    bodies = bodies or {}
    rule_ids = sorted({r for s in scen for r in s["business_rules"]} | set(rules), key=lambda r: int(r.split("-")[1]))
    rule_text = "\n".join(
        f"- {rid}: {rules.get(rid, '(see SPEC section 3)')}"
        + "".join(f"\n    {item}" for item in bodies.get(rid, []))
        for rid in rule_ids
    )
    anchors = [
        "1: Wrong outcome or violates a business rule (e.g. auto-approves a case a rule sends to review).",
        "2: Outcome partly wrong or no business rule cited.",
        "3: Correct outcome but rationale incomplete or cites the wrong rule.",
        "4: Correct outcome, cites the rule(s) that fired, minor gaps.",
        "5: Correct outcome, cites every rule that fired, uses tool data, clear next step.",
    ]
    return {
        "schema": "threadlight-eval-config/v1",
        "generated_by": MARKER,
        "target": {"type": "azure_ai_agent", "name": agent},
        # The hosted agent's "stream": false mode returns only the final answer
        # text; the full SSE stream exhausted the judge's TPM (429) and the
        # eval result size limit (413) in live runs. "new_conversation": true
        # makes every row its own conversation: the Foundry eval sent all rows
        # with one agent_session_id in the 2026-11-07 live run.
        "input_messages": {"input": "{{item.query}}", "stream": False, "new_conversation": True},
        "dataset": "evals/eval_dataset.jsonl",
        "builtin_evaluators": [
            {
                "evaluator_name": name,
                "name": name.split(".", 1)[1],
                "data_mapping": {"query": "{{item.query}}", "response": "{{sample.output_text}}"},
            }
            for name in BUILTIN_EVALUATORS
        ],
        "custom_rubric_evaluators": [
            {
                "name": "spec_business_rules_rubric",
                "type": "score_model",
                "range": [1, 5],
                "threshold": RUBRIC_THRESHOLD,
                "anchors": anchors,
                "derived_from_acceptance_criteria": [s["id"] for s in scen] + rule_ids,
                "system_prompt": (
                    "You grade a business agent's answer against its SPEC. Judge compliance "
                    "against the full rule text below; a rule title is only a label. Business rules:\n"
                    f"{rule_text}\n\nScoring anchors:\n" + "\n".join(anchors)
                    + "\nReturn only the integer score."
                ),
                "user_prompt": (
                    "Request: {{item.query}}\nExpected outcome: {{item.expected}}\n"
                    "Agent answer: {{sample.output_text}}"
                ),
            }
        ],
    }


def build_foundry_manifest(agent: str, cfg: dict[str, Any]) -> dict[str, Any]:
    rubric = cfg["custom_rubric_evaluators"][0]
    return {
        "schema": "threadlight-foundry-package/v1",
        "generated_by": MARKER,
        "agent": {
            "kind": "foundry-hosted",
            "agent_name": agent,
            "agent_id": None,
            "agent_version": None,
            "fallback_active": False,
        },
        "telemetry": {"app_insights_connection_id": None, "trace_id": None},
        "evaluation": {
            "eval_run_id": None,
            "builtin_evaluators": [e["evaluator_name"] for e in cfg["builtin_evaluators"]],
            "custom_rubric_evaluators": [
                {
                    "name": rubric["name"],
                    "anchors": rubric["anchors"],
                    "derived_from_acceptance_criteria": rubric["derived_from_acceptance_criteria"],
                    "threshold": rubric["threshold"],
                    "score": None,
                }
            ],
            "target": dict(cfg["target"]),
        },
    }


